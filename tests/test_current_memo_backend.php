<?php
declare(strict_types=1);
require_once __DIR__.'/../app/bootstrap.php';
require_once __DIR__.'/../app/api.php';
function memo_check(bool $ok,string $label): void {
    if (!$ok) throw new RuntimeException($label);
    echo "PASS: $label\n";
}
$pdo=new PDO('sqlite::memory:');
$pdo->setAttribute(PDO::ATTR_ERRMODE,PDO::ERRMODE_EXCEPTION);
$pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE,PDO::FETCH_ASSOC);
set_db_connection_for_testing($pdo);
$m=db_table_identifier('memo'); $w=db_table_identifier('dashboard_widget');
$pdo->exec("CREATE TABLE $m (memo_id INTEGER PRIMARY KEY AUTOINCREMENT,memo_date TEXT,memo_updated_at TEXT,memo_flag INTEGER,memo_owner INTEGER,memo_title TEXT,memo_body TEXT,memo_format TEXT NOT NULL DEFAULT 'text')");
$pdo->exec("CREATE TABLE $w (widget_id INTEGER PRIMARY KEY AUTOINCREMENT,widget_owner INTEGER,widget_location INTEGER,widget_type TEXT,widget_reference_id INTEGER,widget_sort_order INTEGER,widget_width INTEGER,widget_height INTEGER,widget_style TEXT,widget_config TEXT,widget_flag INTEGER,widget_created_at TEXT,widget_updated_at TEXT)");
$raw="    code\r\n\r\n日本語  \r\n \t";
$normalized=str_replace("\r\n","\n",$raw);
memo_check(dashboard_widget_validate_memo_body($raw)===$normalized,'original whitespace and line endings preserved');
memo_check(dashboard_widget_validate_memo_body(str_repeat('😀',16000))===str_repeat('😀',16000),'16000 four-byte code points fit TEXT');
memo_check(dashboard_widget_validate_memo_body(str_repeat('😀',16001))===null&&dashboard_widget_validate_memo_body(str_repeat('a',16001))===null,'16001 code points rejected');
memo_check(dashboard_widget_validate_memo_body(" \n\t")===null&&dashboard_widget_validate_memo_body("x\x00y")===null&&dashboard_widget_validate_memo_body("\xff")===null,'blank, controls and invalid UTF8 rejected');
$base=['widget_location'=>'0','widget_style'=>'success','widget_width'=>'1','widget_height'=>'2','memo_title'=>'memo','memo_body'=>$raw];
$r=api_dispatch('widget.memo.create',7,$base);
memo_check($r['status']===201,'legacy create defaults to Text');
$id=(int)$r['body']['data']['widget_id']; $mid=(int)$r['body']['data']['memo_id'];
$get=function()use($pdo,$m,$mid){return $pdo->query("SELECT * FROM $m WHERE memo_id=$mid")->fetch();};
$getW=function()use($pdo,$w,$id){return $pdo->query("SELECT * FROM $w WHERE widget_id=$id")->fetch();};
$rev=function()use($get,$getW){return dashboard_widget_memo_revision($get(),$getW());};
memo_check($get()['memo_format']==='text'&&$get()['memo_body']===$normalized,'default format and original body stored');
memo_check(api_dispatch('widget.memo.create',7,$base+['memo_format'=>'html'])['status']===422,'unknown format rejected');
$before=$rev();
$input=['widget_id'=>(string)$id,'memo_body'=>$normalized,'memo_format'=>'markdown','expected_revision'=>$before];
$r=api_dispatch('widget.memo.body.update',7,$input);
memo_check($r['status']===200&&$get()['memo_format']==='markdown'&&$get()['memo_body']===$normalized,'format-only switch preserves exact source');
memo_check($r['body']['data']['memo_revision']===$rev()&&$rev()!==$before,'format-only change invalidates revision');
memo_check(api_dispatch('widget.memo.body.update',7,$input)['status']===409,'stale format revision refused');
memo_check(api_dispatch('widget.memo.body.update',7,['widget_id'=>(string)$id,'memo_body'=>'old','expected_sha256'=>hash('sha256',$normalized)])['status']===409,'old body hash cannot overwrite Markdown');
$now=$rev();
$update=['widget_id'=>(string)$id,'widget_style'=>'primary','widget_width'=>'2','widget_height'=>'2','memo_title'=>'new title','memo_body'=>$normalized,'expected_revision'=>$now];
memo_check(api_dispatch('widget.memo.update',8,$update)['status']===404,'foreign full update denied');
$legacySettings=$update; unset($legacySettings['expected_revision']); $legacySettings['expected_sha256']=hash('sha256',$normalized);
memo_check(api_dispatch('widget.memo.update',7,$legacySettings)['status']===409,'legacy settings cannot overwrite without full revision');
memo_check(api_dispatch('widget.memo.update',7,$update)['status']===200&&$get()['memo_format']==='markdown','settings update retains format if omitted');
memo_check(api_dispatch('widget.memo.body.update',7,['widget_id'=>(string)$id,'memo_body'=>'stale','expected_revision'=>$now])['status']===409,'title and widget settings changes invalidate body draft');
$long=str_repeat('😀',16000);
$r=api_dispatch('widget.memo.body.update',7,['widget_id'=>(string)$id,'memo_body'=>$long,'expected_revision'=>$rev()]);
memo_check($r['status']===200&&$get()['memo_body']===$long&&strlen($get()['memo_body'])===64000,'maximum body stored without truncation');
memo_check(api_dispatch('widget.memo.body.update',8,['widget_id'=>(string)$id,'memo_body'=>'x','expected_revision'=>$rev()])['status']===404,'foreign body update denied');
memo_check(api_dispatch('widget.memo.body.update',7,['widget_id'=>(string)$id,'memo_body'=>'x','memo_format'=>'text','expected_revision'=>'bad'])['status']===422,'invalid revision denied');
$before=$get(); $old=$rev();
$pdo->exec("CREATE TRIGGER fail_memo_layout BEFORE UPDATE ON $w BEGIN SELECT RAISE(ABORT,'forced'); END");
$r=api_dispatch('widget.memo.update',7,array_replace($update,['expected_revision'=>$old,'memo_body'=>'rollback','memo_format'=>'text']));
memo_check($r['status']===503&&$get()===$before&&!$pdo->inTransaction(),'failed settings write rolls back Memo and format');
set_db_connection_for_testing(null);
